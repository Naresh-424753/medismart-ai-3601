EMERGENCY_PATTERNS = [r"chest pain", r"can'?t breathe", r"cannot breathe", r"difficulty breathing", r"shortness of breath", r"unconscious", r"not responding", r"seizure",
                      r"severe bleeding", r"bleeding heavily", r"vomit(ing)? blood", r"slurred speech", r"face drooping", r"weakness on one side", r"stroke", r"heart attack",
                      r"overdose", r"poison", r"snake ?bite", r"suicid", r"kill myself", r"end my life", r"want to die", r"self[- ]harm"]
SELF_HARM = re.compile(r"suicid|kill myself|end my life|want to die|self[- ]harm")


def agents_public() -> list[dict]:
    return [{k: a[k] for k in ("id", "specialist", "icon", "description")} for a in AGENTS]


def suggest(notes: str) -> list[dict]:
    """Ranks agents by how many of their keywords appear in the notes. General Physician is the safe default."""
    t = " " + re.sub(r"\s+", " ", notes.lower()) + " "
    scored = []
    for a in AGENTS:
        hits = [k for k in a["keywords"] if k in t]
        if hits:
            scored.append((len(hits), a, hits))
    # the condition table gives extra signal ("Migraine" -> Neurologist etc. are mapped to the closest agent here)
    scored.sort(key=lambda x: -x[0])
    out = [{**{k: a[k] for k in ("id", "specialist", "icon", "description")}, "reason": "Matches: " + ", ".join(h[:4])} for n, a, h in scored[:3]]
    if not any(o["id"] == "general" for o in out):
        g = BY_ID["general"]
        out.append({**{k: g[k] for k in ("id", "specialist", "icon", "description")}, "reason": "A good first stop for any health concern"})
    return out[:4]


def red_flag(text: str, lang: str | None = None) -> dict | None:
    """Returns a fixed, safe answer when the text describes an emergency (checked before any LLM)."""
    low = text.lower()
    is_emergency = any(re.search(p, low) for p in EMERGENCY_PATTERNS)
    local = languages.emergency_hit(text, lang)
    if not is_emergency and not local:
        return None
    if SELF_HARM.search(low):
        msg = ("I'm really sorry you are going through this, and I'm glad you told me. You deserve support right now. Please call 112 if you are in immediate danger, "
               "or call Tele-MANAS at 14416 (free, 24x7) to talk to a trained counsellor. If someone is with you, please tell them how you feel. I am here to keep talking with you.")
    else:
        msg = local or "This may be an emergency. Please call 112 or 108 now or go to the nearest hospital. Do not wait for an online answer."
    return {"reply": msg, "emergency": True}


def greeting(agent: dict, notes: str = "") -> str:
    first = INTAKE[agent["id"]][0]
    start = f"Hello, I am your AI {agent['specialist']}. I can give general health information, not a diagnosis. "
    return start + (f"You mentioned: \"{notes.strip()[:160]}\". " if notes.strip() else "") + first


def _system_prompt(agent: dict, language: str) -> str:
    return (f"You are {agent['persona']} AI in a patient app in India. Reply in {language} using short, simple sentences (under 90 words). "
            "Ask ONE question at a time to understand the problem (duration, severity, other symptoms, medicines, allergies). "
            "Give general education and safe self-care only. Never diagnose, never prescribe prescription-only medicines or doses. "
            "If symptoms sound serious or last long, advise seeing a doctor. For emergencies tell the user to call 112 or 108. Stay within your specialty and say so if asked about something else.")


async def _llm(system: str, messages: list[dict], max_tokens: int = 500, search: bool = True) -> str | None:
    if gemini.enabled():
        g = await gemini.generate(system, messages, max_tokens, search)
        if g:
            return g
    key = os.getenv("LLM_API_KEY")
    if not key:
        return None
    try:
        import httpx
        async with httpx.AsyncClient(timeout=40) as c:
            r = await c.post("https://api.anthropic.com/v1/messages", headers={"x-api-key": key, "anthropic-version": "2023-06-01", "content-type": "application/json"},
                             json={"model": os.getenv("LLM_MODEL", "claude-sonnet-5-5"), "max_tokens": max_tokens, "system": system, "messages": messages})
            r.raise_for_status()
            return "".join(b.get("text", "") for b in r.json().get("content", [])).strip() or None
    except Exception:
        return None


def _user_turns(messages: list[dict]) -> int:
    return sum(1 for m in messages if m["role"] == "user")


def _rules_reply(agent: dict, messages: list[dict], text: str) -> str:
    qs = INTAKE[agent["id"]]
    n = _user_turns(messages)  # includes the message just added
    if n < len(qs):
        return "Thank you, I have noted that. " + qs[n]
    allt = " ".join(m["content"] for m in messages if m["role"] == "user")
    res = symptoms.check([], allt)
    advice = "Rest, drink enough fluids and watch how you feel over the next day or two."
    if res["possible_conditions"]:
        top = res["possible_conditions"][0]
        advice = f"{top['self_care']} (This is general information, not a diagnosis.)"
    return ("Thank you, that is enough for me to summarise. " + advice + " If it gets worse, lasts more than 2-3 days, or you feel unsure, please see a doctor. "
            "Tap \"End and get report\" to get a summary you can show your doctor.")


async def reply(agent: dict, messages: list[dict], text: str, language: str = "English") -> tuple[str, str]:
    """messages already contains the new user message. Returns (reply, source)."""
    llm = await _llm(_system_prompt(agent, language), [{"role": m["role"], "content": m["content"]} for m in messages[-14:]], 400)
    if llm:
        return llm, "llm"
    return _rules_reply(agent, messages, text), "rules"


# ---------------------------------------------------------------- report
_DUR = re.compile(r"(\d+|a|one|two|three|four|five|few|couple of)\s*(days|day|weeks|week|months|month|hours|hour|years|year)", re.I)


def _severity(text: str, urgency: str) -> str:
    t = text.lower()
    if urgency == "emergency" or re.search(r"\b(severe|unbearable|very bad|worst|[89]/10|10/10|9 out of 10|8 out of 10)\b", t):
        return "severe"
    if re.search(r"\b(moderate|[5-7]/10|quite|a lot)\b", t):
        return "moderate"
    return "mild"


def _meds(text: str) -> list[str]:
    found = []
    for w in set(re.findall(r"[A-Za-z][A-Za-z\-]{3,}", text)):
        c = drugs.canon(w)
        if c and c not in found:
            found.append(c)
    return found


def rules_report(agent: dict, messages: list[dict], emergency: bool, notes: str = "") -> dict:
    user_text = (notes + " " + " ".join(m["content"] for m in messages if m["role"] == "user")).strip()
    chk = symptoms.check([], user_text)
    first = notes.strip() or next((m["content"] for m in messages if m["role"] == "user"), "")
    dur = _DUR.search(user_text)
    recs = []
    if chk["possible_conditions"]:
        recs.append(chk["possible_conditions"][0]["self_care"])
    if emergency or chk["urgency"] == "emergency":
        recs.insert(0, "Call 112 or 108 or go to the nearest hospital now.")
    elif chk["urgency"] == "see_doctor":
        recs.append("Book an appointment with a doctor in the next few days.")
    recs.append("See a doctor if symptoms get worse or last more than 2-3 days.")
    return {"agent": agent["specialist"], "chief_complaint": first[:200], "summary": f"Conversation with the AI {agent['specialist']}. Reported: {first[:240]}",
            "symptoms": chk["symptoms"][:12], "duration": dur.group(0) if dur else "not stated", "severity": _severity(user_text, "emergency" if emergency else chk["urgency"]),
            "medicines_mentioned": _meds(user_text), "recommendations": recs[:5],
            "suggested_specialist": (chk["possible_conditions"][0]["specialist"] if chk["possible_conditions"] else agent["specialist"]),
            "source": "rules"}


async def make_report(agent: dict, messages: list[dict], emergency: bool, language: str = "English", notes: str = "") -> dict:
    base = rules_report(agent, messages, emergency, notes)
    convo = (f"INITIAL NOTES: {notes}\n" if notes else "") + "\n".join(f"{m['role'].upper()}: {m['content']}" for m in messages[-30:])
    prompt = ("From this conversation write a JSON object ONLY (no markdown) with keys: chief_complaint (1 sentence), summary (2-3 sentences), symptoms (list), duration, "
              "severity (mild|moderate|severe), medicines_mentioned (list), recommendations (list of 3-5 short safe items), suggested_specialist. Do not diagnose.\n\n" + convo)
    txt = await _llm("You summarise patient conversations for a doctor. Output valid JSON only.", [{"role": "user", "content": prompt}], 1200, search=False)
    if txt:
        try:
            data = json.loads(re.sub(r"^```(?:json)?|```$", "", txt.strip(), flags=re.M).strip())
            for k in ("chief_complaint", "summary", "symptoms", "duration", "severity", "medicines_mentioned", "recommendations", "suggested_specialist"):
                if k in data and data[k]:
                    base[k] = data[k]
            if base.get("severity") not in ("mild", "moderate", "severe"):
                base["severity"] = "mild"
            if emergency:
                base["severity"] = "severe"
            base["source"] = "llm"
        except Exception:
            pass
    base["disclaimer"] = "AI-generated summary for information only. It is not a diagnosis or a prescription. Please consult a doctor."
    return base
